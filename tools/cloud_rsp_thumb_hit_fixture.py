#!/usr/bin/env python3
"""One bounded synthetic Thumb Z0 breakpoint-hit probe, NEVER private/game data.

Exactly one c packet may be emitted, only after authentic read-only ?/g/m,
generated ROM bytes and Thumb width-2 Z0 are validated. No s, Ctrl-C, guest
writes, save, host input or arbitrary ROM path. On non-stop/timeouts the
entire disposable mGBA subprocess is terminated, not left running.
"""
from __future__ import annotations

import os
from pathlib import Path
import socket
import subprocess
import sys
import tempfile
import time

from cloud_mgba_rsp_fixture import HOST, PORT, encode_rsp, recv_rsp, request
from cloud_rsp_netns_gate import inspect_network, check_no_egress
from cloud_rsp_thumb2_fixture import (
    ARM_LDR, THUMB_LOOP, THUMB_READ, THUMB_SET, THUMB_REMOVE,
    make_thumb_fixture, thumb_memory, thumb_breakpoint,
)
from pr26_exact_probe_parser_reference import parse_stop, parse_registers

ALLOWED_CONTINUE = b"c"
TARGET_PC = 0x08000100
ALLOWED_STOP_PCS = frozenset((TARGET_PC, TARGET_PC + 2, TARGET_PC + 4))
STOP_SIGNALS = frozenset(("S05", "T05"))


class HitError(RuntimeError):
    """The public fixture did not prove one authentic generated-ROM hit."""


def one_continue(sock: socket.socket, command: bytes) -> bytes:
    if command != ALLOWED_CONTINUE:
        raise ValueError("only one fixture continue packet allowed")
    sock.sendall(encode_rsp(command))
    # If target does not hit, socket.timeout is a HARD FAILURE and the caller
    # kills the disposable emulator. recv_rsp enforces bounded frame bytes.
    return recv_rsp(sock)


def validate_hit(
    stop: bytes, regs: bytes, *, diagnostic_nonstandard: bool = False
) -> int:
    # PR26's original strict parser is untouched. The ONLY nonstandard
    # compatibility candidate is the exact observed public mGBA 0.10.5
    # frame S05k, requiring independent register-PC corroboration.
    if diagnostic_nonstandard and stop == b"S05k":
        parsed_stop = "S05k"
    else:
        parsed_stop = parse_stop(stop)
    if parsed_stop[:3] not in STOP_SIGNALS:
        raise HitError("GDB did not report a SIGTRAP/05 stop")
    cpu = parse_registers(regs)
    pc = cpu[15]
    if pc not in ALLOWED_STOP_PCS:
        # Only a self-generated PUBLIC fixture is ever run; bounded PC metadata
        # is safe for diagnosis, but NEVER use this with private ROMs.
        raise HitError("GDB stop PC outside generated Thumb target: " + hex(pc))
    return pc


def run_one_hit(sock: socket.socket) -> tuple[int, str, bool]:
    """Preflight -> Z0 -> single c -> verified trap/PC -> z0 (if stopped).

    A lost stop reply cannot be cleaned up in-band without issuing further
    run control. In that case raise and let caller terminate mGBA immediately.
    """
    # Read-only preflight, no c until all explicit generated bytes pass.
    initial = parse_stop(request(sock, b"?"))
    before = parse_registers(request(sock, b"g"))
    if len(before) != 16:
        raise HitError("missing real register parse")
    arm = request(sock, b"m080000c0,4")
    if arm.lower() != b"00009fe5":
        raise HitError("synthetic ROM ARM entry not mapped")
    if thumb_memory(sock, THUMB_READ).lower() != b"fee7":
        raise HitError("synthetic ROM Thumb instruction not mapped")

    install_attempted = False
    continued = False
    definitely_stopped = False
    try:
        install_attempted = True
        thumb_breakpoint(sock, THUMB_SET)
        continued = True  # mark BEFORE c could resume the guest
        stop_reply = one_continue(sock, ALLOWED_CONTINUE)
        # Original GENERATED test ROM only: report a bounded protocol shape,
        # never treat a non-stop acknowledgement as a successful CPU trap.
        nonstandard = False
        try:
            stop = parse_stop(stop_reply)
        except ValueError as error:
            if stop_reply == b"S05k":
                # Nonstandard mGBA 0.10.5 PUBLIC fixture observation ONLY.
                # This is NOT made valid under original PR26's parser.
                stop = "S05k"
                nonstandard = True
            else:
                raise HitError(
                    "generated-fixture continue returned NON-STOP RSP frame "
                    "len=" + str(len(stop_reply)) +
                    " prefix_hex=" + stop_reply[:16].hex()
                ) from error
        if stop[:3] not in STOP_SIGNALS:
            raise HitError("received a CPU stop that is not SIGTRAP: " + stop[:3])
        definitely_stopped = True
        regs = request(sock, b"g")
        pc = validate_hit(stop_reply, regs, diagnostic_nonstandard=nonstandard)
        return pc, stop, nonstandard
    finally:
        if install_attempted and (not continued or definitely_stopped):
            # Once a stop reply has been received, exactly one bounded cleanup.
            try:
                thumb_breakpoint(sock, THUMB_REMOVE)
            except (OSError, RuntimeError, ValueError) as exc:
                raise HitError("failed to remove public generated Thumb breakpoint") from exc
        # If c had no trustworthy stop, do NOT send further control or claim
        # cleanup; caller MUST kill/await the disposable process on exception.


def main() -> None:
    if len(sys.argv) != 1 or "SOULGOLD_ALLOW_PRIVATE_INPUTS" in os.environ:
        raise RuntimeError("synthetic breakpoint-hit fixture forbids private paths/flags")

    inspect_network()
    check_no_egress()
    with tempfile.TemporaryDirectory(prefix="sg-public-hit-only-") as folder:
        root = Path(folder)
        rom = root / "original_generated_thumb_hit.gba"
        rom.write_bytes(make_thumb_fixture())
        rom.chmod(0o600)
        home = root / "home"
        home.mkdir(mode=0o700)
        env = {k: os.environ[k] for k in ("PATH", "DISPLAY", "XAUTHORITY") if k in os.environ}
        env.update(HOME=str(home), SDL_AUDIODRIVER="dummy")
        process = subprocess.Popen(
            ["mgba", "-g", str(rom)], cwd=root, env=env,
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        try:
            deadline = time.monotonic() + 20
            conn = None
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise HitError("mGBA exited before read-only GDB preflight")
                try:
                    conn = socket.create_connection((HOST, PORT), timeout=1)
                    break
                except OSError:
                    time.sleep(.2)
            if conn is None:
                raise HitError("real generated-ROM debugger listener unavailable")
            with conn as sock:
                sock.settimeout(3.0)
                listeners = inspect_network(require_listener=True)
                check_no_egress()
                pc, stop, nonstandard = run_one_hit(sock)
            if nonstandard:
                print("EVIDENCE_ONLY: generated Thumb target PC corroborates NONSTANDARD mGBA S05k response")
                print("PR26_STOP_GRAMMAR: REJECTS S05k (original strict parser unchanged)")
            else:
                print("PASS: real hosted spec-conforming mGBA synthetic Thumb breakpoint HIT")
            print("SYNTHETIC_STOP_SIGNAL: " + stop[:3])
            print("SYNTHETIC_STOP_PC: " + hex(pc))
            print("GENERATED_TARGET_PC: " + hex(TARGET_PC))
            print("GDB_LISTENER_IN_NO_NETWORK_NAMESPACE: " + repr(listeners))
            print("ONLY_ONE_C: exactly one continue; NO s/host input, no private data")
            print("SOULGOLD_NATIVE_ACCEPTANCE: 0/20, production 0 percent")
        finally:
            # ALWAYS kill a running fixture on any uncertain RSP stop/timeout.
            if process.poll() is None:
                process.terminate()
            try:
                process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=3)


if __name__ == "__main__":
    main()
